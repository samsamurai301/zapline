#!/usr/bin/env bash
# Token-efficiency benchmark: what an AI assistant reads and writes to build
# and fix the same small API with zapline, axum and actix-web.
#
#   ./run.sh            # writes results.md
#
# Needs cargo, node and npm. Tokens are counted with o200k_base (count.mjs).
set -euo pipefail
# Cargo's defaults, as most people run it (no backtraces).
export RUST_BACKTRACE=0
cd "$(dirname "$0")"
ROOT=$(cd ../.. && pwd)
[ -d node_modules ] || npm install --silent
count() { node count.mjs "$@" | cut -f1; }
tokens_of() { node count.mjs - | cut -f1; }

cargo build -q --manifest-path "$ROOT/Cargo.toml" -p zapline-cli
ZAPLINE="$ROOT/target/debug/zapline"
cargo test -q >/dev/null 2>&1 # warm the build so timings and output are stable

work=$(mktemp -d)
trap 'cp src/bin/zapline.rs.orig src/bin/zapline.rs 2>/dev/null; rm -f src/bin/zapline.rs.orig; rm -rf "$work"' EXIT
cp src/bin/zapline.rs src/bin/zapline.rs.orig

# 1. Code: the same API (CRUD, validation with field errors, 404s, OpenAPI,
#    interactive docs, one end-to-end test), formatted with rustfmt.
z=$(count src/bin/zapline.rs); a=$(count src/bin/axum.rs); x=$(count src/bin/actix.rs)

# 2. A failing test: what the assistant reads back.
sed -i.bak 's/assert_status(201)/assert_status(200)/' src/bin/zapline.rs && rm -f src/bin/zapline.rs.bak
raw_test=$(cargo test --bin zapline 2>&1 | tokens_of || true)
brief_test=$("$ZAPLINE" test 2>/dev/null | tokens_of || true)
cp src/bin/zapline.rs.orig src/bin/zapline.rs

# 3. A compile error.
sed -i.bak 's/Json(store.0.lock().unwrap().values().cloned().collect())/Json(store.0.lock().unwrap().len())/' src/bin/zapline.rs && rm -f src/bin/zapline.rs.bak
raw_check=$(cargo check --bin zapline 2>&1 | tokens_of || true)
brief_check=$("$ZAPLINE" check 2>/dev/null | tokens_of || true)
cp src/bin/zapline.rs.orig src/bin/zapline.rs

# 4. Learning the framework: the docs an assistant loads before writing code.
cheat=$(node -e 'process.stdout.write(require("fs").readFileSync(process.argv[1],"utf8"))' "$ROOT/docs/src/cheatsheet.md" | tokens_of)
cheat_ex=$(count "$ROOT/examples/examples/cheatsheet.rs")

pct() { awk -v a="$1" -v b="$2" 'BEGIN { printf "%.0f%%", (1 - a / b) * 100 }'; }

cat > results.md <<MD
# Token benchmark results

Generated by \`bench/tokens/run.sh\` on $(date -u +%Y-%m-%d). Tokens: o200k_base.

## Writing the app

The same notes API in each framework: list, create (validated, 422 with field errors), fetch (404), delete,
an OpenAPI document, interactive docs, and one end-to-end test. Sources: [\`src/bin/\`](src/bin/).

| Framework | Tokens | vs zapline |
|---|---:|---:|
| zapline | $z | |
| axum 0.8 + utoipa + validator | $a | zapline uses $(pct "$z" "$a") fewer |
| actix-web 4 + utoipa + validator | $x | zapline uses $(pct "$z" "$x") fewer |

## Reading tool output

| Situation | cargo | zapline | Saved |
|---|---:|---:|---:|
| One failing test (\`cargo test\` vs \`zapline test\`) | $raw_test | $brief_test | $(pct "$brief_test" "$raw_test") |
| One type error (\`cargo check\` vs \`zapline check\`) | $raw_check | $brief_check | $(pct "$brief_check" "$raw_check") |

## Learning the framework

The cheatsheet page, which \`AGENTS.md\`, \`llms.txt\` and \`zapline mcp\` point assistants to first: $cheat tokens
(its runnable example alone: $cheat_ex). \`zapline mcp\`'s \`docs\` tool answers a topic with only the matching
guide sections instead of the whole guide.
MD
cat results.md
