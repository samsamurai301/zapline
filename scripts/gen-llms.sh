#!/usr/bin/env bash
# Generate docs/src/llms.txt and docs/src/llms-full.txt from the guide.
#
#   ./scripts/gen-llms.sh            # write both files
#   ./scripts/gen-llms.sh --check    # fail if they are out of date (CI)
#
# llms.txt follows https://llmstxt.org: a short index of the guide with one
# link per page. llms-full.txt is the whole guide in reading order as one
# Markdown file, so an AI assistant can load all of zapline's docs in a
# single fetch. mdBook copies both files to the published site, and the CLI
# embeds llms-full.txt for its MCP `docs` tool, and the diagnostic code
# registry (crates/zapline/src/codes.in) for `zapline explain`.
set -euo pipefail
cd "$(dirname "$0")/.."

SITE=${SITE:-https://samsamurai301.github.io/zapline}
SRC=docs/src
# The guide embedded in the CLI for `zapline mcp` (inside the crate so it is published).
GUIDE=crates/zapline-cli/assets/guide.md
# The diagnostic code registry, embedded in the CLI the same way.
CODES_SRC=crates/zapline/src/codes.in
CODES=crates/zapline-cli/assets/codes.in
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Pages in SUMMARY.md order: lines like `- [Title](file.md)` or `[Title](file.md)`.
# Section headings (`# Core concepts`) become llms.txt sections.
{
  echo "# zapline"
  echo
  echo "> zapline is a fast, batteries-included Rust web framework: FastAPI-style typed handlers, OpenAPI 3.1 generated from code, validation, DI, auth, sessions, WebSockets, metrics and a thread-per-core server. One prelude (\`use zapline::prelude::*\`), route macros, \`App::new().mount(..).run(addr)\`, and an in-process test client (\`app.test()\`)."
  echo
  echo "Conventions an assistant should follow: handlers are \`async fn\` with extractor arguments (\`Path\`, \`Query\`, \`Json\`, \`Valid<Json<T>>\`, \`State\`, \`Dep\`); errors are \`zapline::Result<T>\` with \`Error::not_found()\` and friends plus \`.with_code(\"snake_case\")\`; no \`#[tokio::main]\` (\`App::run\` owns the runtime); middleware is \`async fn(Request, Next) -> Response\`."
  echo
  echo "- [Cheatsheet]($SITE/cheatsheet.html): start here; one runnable file with the canonical way to do each common task (~3k tokens)"
  echo "- [Whole guide as one file]($SITE/llms-full.txt): every page below, concatenated"
  echo "- [API reference]($SITE/api/zapline/): rustdoc for the \`zapline\` crate"
  echo "- [Source](https://github.com/samsamurai301/zapline)"
} > "$tmp/llms.txt"

{
  echo "# The zapline Guide (single file)"
  echo
  echo "Source: $SITE/ — generated by scripts/gen-llms.sh; do not edit by hand."
} > "$tmp/llms-full.txt"

section=""
link_re='\[([^]]+)\]\(([^)]+)\.md\)'
while IFS= read -r line; do
  if [[ $line =~ ^#\ (.+)$ ]]; then
    [ "${BASH_REMATCH[1]}" = "Summary" ] && continue
    section=${BASH_REMATCH[1]}
    printf '\n## %s\n\n' "$section" >> "$tmp/llms.txt"
    continue
  fi
  if [[ $line =~ $link_re ]]; then
    title=${BASH_REMATCH[1]}
    file=${BASH_REMATCH[2]}
    [ -z "$section" ] && { section="Overview"; printf '\n## Overview\n\n' >> "$tmp/llms.txt"; }
    # First paragraph line after the H1 as the one-line description.
    desc=$(awk 'NR>1 && /^([A-Za-z*]|`[^`])/ {print; exit}' "$SRC/$file.md" | cut -c1-160)
    echo "- [$title]($SITE/$file.html): $desc" >> "$tmp/llms.txt"
    {
      printf '\n\n---\n\n<!-- %s.md -->\n\n' "$file"
      # mdBook `{{#include ...}}` directives and hidden doctest lines (`# `)
      # inside rust blocks are noise for a reader; drop them.
      awk -v src="$SRC" '
        /^```/ { inrust = ($0 ~ /^```rust/) ? !inrust : 0 }
        match($0, /\{\{#include [^}]+\}\}/) {
          path = substr($0, RSTART + 11, RLENGTH - 13)
          while ((getline inc < (src "/" path)) > 0) print inc
          close(src "/" path)
          next
        }
        /\{\{#/ { next }
        inrust && /^# / { next }
        inrust && /^#$/ { next }
        { print }
      ' "$SRC/$file.md"
    } >> "$tmp/llms-full.txt"
  fi
done < "$SRC/SUMMARY.md"

if [ $CHECK = 1 ]; then
  diff -q "$tmp/llms.txt" "$SRC/llms.txt" >/dev/null && diff -q "$tmp/llms-full.txt" "$SRC/llms-full.txt" >/dev/null \
    && diff -q "$tmp/llms-full.txt" "$GUIDE" >/dev/null && diff -q "$CODES_SRC" "$CODES" >/dev/null || {
    echo "docs/src/llms*.txt, $GUIDE or $CODES are out of date: run ./scripts/gen-llms.sh" >&2
    exit 1
  }
  echo "llms.txt and llms-full.txt are up to date"
else
  cp "$tmp/llms.txt" "$tmp/llms-full.txt" "$SRC/"
  cp "$tmp/llms-full.txt" "$GUIDE"
  cp "$CODES_SRC" "$CODES"
  echo "wrote $SRC/llms.txt ($(wc -c < "$SRC/llms.txt") bytes) and $SRC/llms-full.txt ($(wc -c < "$SRC/llms-full.txt") bytes)"
fi
